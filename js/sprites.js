function art(w, lines) {
    const rows = [];
    for (let i = 0; i < lines.length; i++) {
        const line = lines[i];
        if (line.length !== w) {
            throw new Error("Sprite row " + i + " is " + line.length + " wide, expected " + w + " [" + line + "]");
        }
        rows.push(line);
    }
    return rows;
}

