const Sprites = {
    cache: {},

    build() {
        const keys = Object.keys(ART);
        for (let i = 0; i < keys.length; i++) {
            const key = keys[i];
            this.cache[key] = bakeSprite(ART[key], SPRITE_SCALE[key] || 2);
        }
    },

    draw(ctx, key, x, y, flip) {
        const canvas = this.cache[key];
        if (!canvas) return;
        const w = canvas.width;
        const h = canvas.height;
        ctx.imageSmoothingEnabled = false;
        if (flip) {
            ctx.save();
            ctx.translate(Math.round(x), Math.round(y));
            ctx.scale(-1, 1);
            ctx.drawImage(canvas, Math.round(-w / 2), Math.round(-h / 2));
            ctx.restore();
        } else {
            ctx.drawImage(canvas, Math.round(x - w / 2), Math.round(y - h / 2));
        }
    },

    heroKey(id, facing) {
        if (Math.abs(facing.x) > Math.abs(facing.y)) return id + "-side";
        if (facing.y < 0) return id + "-up";
        return id + "-down";
    },

    heroFlip(facing) {
        return Math.abs(facing.x) > Math.abs(facing.y) && facing.x < 0;
    },

    drawBlade(ctx, x, y, facing, length, color, wide) {
        const ang = Math.atan2(facing.y, facing.x);
        const x1 = x + Math.cos(ang) * 8;
        const y1 = y + Math.sin(ang) * 8;
        const x2 = x + Math.cos(ang) * length;
        const y2 = y + Math.sin(ang) * length;
        ctx.save();
        ctx.lineCap = "round";
        ctx.strokeStyle = color;
        ctx.globalAlpha = 0.35;
        ctx.lineWidth = (wide || 3) + 5;
        ctx.beginPath();
        ctx.moveTo(x1, y1);
        ctx.lineTo(x2, y2);
        ctx.stroke();
        ctx.globalAlpha = 1;
        ctx.lineWidth = wide || 3;
        ctx.stroke();
        ctx.strokeStyle = PALETTE.foam;
        ctx.lineWidth = 1;
        ctx.stroke();
        ctx.restore();
    },

    drawSwing(ctx, x, y, facing, range, color, swing, dur) {
        const ang = Math.atan2(facing.y, facing.x);
        const spanTime = dur || 0.22;
        const along = 1 - Math.max(0, Math.min(1, swing / spanTime));
        const span = 1.7;
        const a0 = ang - span * 0.62 + along * span;
        const a1 = a0 + span * 0.55;
        const radius = Math.max(18, range * 0.86);
        ctx.save();
        ctx.lineCap = "round";
        ctx.strokeStyle = color;
        ctx.globalAlpha = 0.28;
        ctx.lineWidth = 14;
        ctx.beginPath();
        ctx.arc(x, y, radius, a0, a1);
        ctx.stroke();
        ctx.globalAlpha = 0.95;
        ctx.lineWidth = 5;
        ctx.stroke();
        ctx.strokeStyle = PALETTE.foam;
        ctx.lineWidth = 2;
        ctx.stroke();
        const tip = a0 + (a1 - a0) * 0.85;
        const tx = x + Math.cos(tip) * radius;
        const ty = y + Math.sin(tip) * radius;
        ctx.globalAlpha = 1;
        ctx.fillStyle = PALETTE.foam;
        ctx.beginPath();
        ctx.arc(tx, ty, 5, 0, Math.PI * 2);
        ctx.fill();
        ctx.fillStyle = color;
        ctx.beginPath();
        ctx.arc(tx, ty, 3, 0, Math.PI * 2);
        ctx.fill();
        ctx.restore();
    },

    drawAim(ctx, x, y, facing, color, strong) {
        const fx = facing && facing.x ? facing.x : 0;
        const fy = facing && facing.y ? facing.y : 0;
        const ang = fx || fy ? Math.atan2(fy, fx) : Math.PI / 2;
        const dist = strong ? 36 : 26;
        ctx.save();
        ctx.translate(x, y);
        ctx.rotate(ang);
        ctx.strokeStyle = PALETTE.foam;
        ctx.globalAlpha = strong ? 1 : 0.85;
        ctx.lineWidth = strong ? 3 : 2;
        ctx.beginPath();
        ctx.moveTo(12, 0);
        ctx.lineTo(dist - 4, 0);
        ctx.stroke();
        ctx.translate(dist, 0);
        ctx.fillStyle = color;
        ctx.globalAlpha = 1;
        ctx.beginPath();
        ctx.moveTo(10, 0);
        ctx.lineTo(-8, 7);
        ctx.lineTo(-4, 0);
        ctx.lineTo(-8, -7);
        ctx.closePath();
        ctx.fill();
        ctx.fillStyle = PALETTE.foam;
        ctx.fillRect(-2, -1, 7, 2);
        ctx.restore();
    },
};

function bakeSprite(rows, scale) {
    const h = rows.length;
    const w = rows[0].length;
    const canvas = document.createElement("canvas");
    canvas.width = w * scale;
    canvas.height = h * scale;
    const g = canvas.getContext("2d");
    g.imageSmoothingEnabled = false;
    for (let y = 0; y < h; y++) {
        for (let x = 0; x < w; x++) {
            const ch = rows[y][x];
            if (ch === "." || !SPRITE_INK[ch]) continue;
            g.fillStyle = SPRITE_INK[ch];
            g.fillRect(x * scale, y * scale, scale, scale);
        }
    }
    return canvas;
}
